function subject({
  category,
  subtopic,
  title,
  illustrationType,
  keywords,
  description,
}) {
  const titleSlug = title
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return {
    category,
    subtopic,
    title,
    slug: `${category}-${subtopic}-${titleSlug}`,
    illustrationType,
    keywords,
    description,
    storagePath: `${category}/${subtopic}/${titleSlug}.webp`,
    photoQueries: PHOTO_QUERIES[illustrationType] ?? [`${title} photograph`],
    photoFiles: PHOTO_FILES[illustrationType] ?? [],
    photoRequire: PHOTO_REQUIRE[illustrationType] ?? [],
  };
}

