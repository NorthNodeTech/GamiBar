export function getLibrarySubjects({ category, limit } = {}) {
  const perSubtopic = Math.max(1, IMAGES_PER_SUBTOPIC);
  const grouped = new Map();
  for (const item of ALL_SUBJECTS) {
    const key = `${item.category}/${item.subtopic}`;
    const list = grouped.get(key) ?? [];
    if (list.length < perSubtopic) list.push(item);
    grouped.set(key, list);
  }
  let subjects = [...grouped.values()].flat();
  if (category) {
    const slug = String(category).toLowerCase();
    subjects = subjects.filter((item) => item.category === slug);
  }
  if (Number.isFinite(limit) && limit > 0) {
    subjects = subjects.slice(0, limit);
  }
  return subjects;
}

export function getAllConfiguredSubjects() {
  return ALL_SUBJECTS;
}
